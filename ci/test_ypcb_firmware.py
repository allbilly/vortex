def test_overlay_accepts_only_bram_changes(overlay):
    image, candidate, proof = overlay
    path = candidate / 'gateware/ypcb_ddr3.v'
    path.write_text(path.read_text().replace('10:00:00', '10:01:00').replace('metadata', 'other hierarchy'))
    binding, payload = firmware.prepare_overlay(image, candidate, proof)
    assert binding['original_firmware_id'] == 1
    assert payload == b'\x13\0\0\0\x32\x54\x76\x98'


@pytest.mark.parametrize('change', ['logic', 'csr', 'ram', 'binary', 'identity', 'proof', 'proof_source', 'frozen', 'boot'])
def test_overlay_rejects_changes(overlay, change):
    image, candidate, proof = overlay
    path = candidate / 'gateware/ypcb_ddr3.v'
    if change == 'logic':
        path.write_text(path.read_text().replace('module test;', 'module other;'))
    elif change == 'csr':
        (candidate / 'csr.json').write_text('{}')
    elif change == 'ram':
        path.write_text(path.read_text().replace("selfcal_mem[0] = 'h00000013", "selfcal_mem[0] = 'h00000012"))
    elif change == 'binary':
        (candidate / 'selfcal_fw/firmware.bin').write_bytes(b'changed!')
    elif change == 'identity':
        path = candidate / 'selfcal_fw/manifest.json'
        d = json.loads(path.read_text()); d['firmware_id'] ^= 1; write_json(path, d)
    elif change == 'proof':
        d = json.loads(proof.read_text()); d['rtl_exit']['exit_code'] = 1; write_json(proof, d)
    elif change == 'proof_source':
        source = Path(next(iter(json.loads(proof.read_text())['source_sha256'])))
        source.write_text('changed source')
    elif change == 'frozen':
        (image / 'ddr/selfcal_fw/firmware.bin').write_bytes(b'bad!')
    elif change == 'boot':
        d = json.loads(proof.read_text()); d['boot_firmware_sha256'] = '0' * 64; write_json(proof, d)
    with pytest.raises(ValueError):
        firmware.prepare_overlay(image, candidate, proof)


OFFSETS = dict(zip(['hold', 'status', 'state', 'mem_adr', 'mem_dat', 'mem_rdat', 'mbox_adr', 'mbox_dat'],
                   [0x6008, 0x600c, 0x6010, 0x601c, 0x6020, 0x6024, 0x6014, 0x6018]))


class CpuMmio:
    def __init__(self):
        self.board, self.version, self.state = 0x40022, 3, 3
        self.held = False
        self.never_held = False
        self.address = self.pointer = self.calls = self.written = self.verified = self.restarts = 0
        self.corrupt = -1
        self.fail_at = -1
        self.result_id = 0x78dc1fa8
        self.memory = [0xcccccccc] * 4096
        self.writes = []

    def access(self):
        self.calls += 1
        if self.calls == self.fail_at:
            raise IOError('injected MMIO failure')

    def read(self, address):
        self.access()
        if address == 0x3000: return 0x56595043
        if address == 0x3004: return self.version
        if address == 0x3008: return self.board
        if address == OFFSETS['status']: return firmware.CPU_HELD if self.held else firmware.CPU_RUNNING
        if address == OFFSETS['state']: return self.state
        if address == OFFSETS['mem_rdat']:
            assert self.held
            self.verified += 1
            return self.memory[self.address] ^ (1 if self.address == self.corrupt else 0)
        if address == OFFSETS['mbox_dat']:
            return {0: 0x59444331, 1: self.result_id, 2: 3, 3: 2, 4: 8, 5: 6936}.get(self.pointer, 0)
        raise AssertionError(hex(address))

    def write(self, address, value):
        self.access()
        self.writes.append((address, value))
        if address == OFFSETS['hold']:
            if value == 0:
                assert self.written == self.verified == 4096
                self.restarts += 1
                self.state = 3
            self.held = bool(value) and not self.never_held
        elif address == OFFSETS['state']:
            assert self.held and value == 0
            self.state = value
        elif address == OFFSETS['mem_adr']:
            assert self.held and 0 <= value < 4096
            self.address = value
        elif address == OFFSETS['mem_dat']:
            assert self.held
            self.memory[self.address] = value
            self.written += 1
        elif address == OFFSETS['mbox_adr']:
            assert 0 <= value < 128
            self.pointer = value
        else:
            raise AssertionError('Upload touched non-CPU register ' + hex(address))

    def now(self):
        return self.calls * 0.001


def capture(mmio, **kwargs):
    return firmware.upload_and_capture(mmio, b'\x13\0\0\0\x32\x54\x76\x98', 0x78dc1fa8,
                                        OFFSETS, now=mmio.now, **kwargs)


def test_upload_full_padded_memory_and_restart():
    mmio = CpuMmio(); report = capture(mmio)
    assert mmio.memory == [0x13, 0x98765432] + [0] * 4094
    assert report['words_written'] == report['words_verified'] == 4096
    assert report['state'] == 3 and report['failed_lane'] == 8
    assert not report['gpu_runtime_qualified'] and report['final_board_status'] >> 16 == 4
    assert not mmio.held and mmio.restarts == 1


@pytest.mark.parametrize('board', [0, 3, 0x30002, 0x20002, 0x10002, 0x40062, 0x40222, 0x40822])
def test_upload_rejects_active_or_invalid_board(board):
    mmio = CpuMmio(); mmio.board = board
    with pytest.raises(ValueError): capture(mmio)
    assert mmio.writes == []


@pytest.mark.parametrize('word', [0, 7, 4095])
def test_readback_failure_never_restarts(word):
    mmio = CpuMmio(); mmio.corrupt = word
    with pytest.raises(ValueError, match='readback mismatch'): capture(mmio)
    assert mmio.held and mmio.restarts == 0


@pytest.mark.parametrize('access', [1, 6, 9, 1024, 8200, 12000, 16398])
def test_upload_io_failures_stay_held(access):
    mmio = CpuMmio(); mmio.fail_at = access
    with pytest.raises(IOError): capture(mmio)
    if access > 5: assert mmio.held


def test_hold_timeout_and_cancel_do_not_start():
    mmio = CpuMmio(); mmio.never_held = True
    with pytest.raises(TimeoutError): capture(mmio, timeout=0.02)
    assert mmio.written == mmio.restarts == 0
    mmio = CpuMmio()
    with pytest.raises(InterruptedError): capture(mmio, cancelled=lambda: mmio.written > 10)
    assert mmio.held and mmio.restarts == 0


def test_firmware_identity_after_restart_is_required():
    mmio = CpuMmio(); mmio.result_id ^= 1
    with pytest.raises(ValueError, match='does not match'): capture(mmio)
    assert mmio.held and mmio.restarts == 1
