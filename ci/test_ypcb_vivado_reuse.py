import hashlib
import json
from pathlib import Path
import runpy

import pytest


@pytest.mark.parametrize('change', ['timestamps', 'logic', 'attribute', 'other_file'])
def test_reuse_generated_cdc(tmp_path, change):
    root = Path((Path.cwd() / 'config.mk').read_text().split('VORTEX_HOME ?= ', 1)[1].splitlines()[0])
    reuse = runpy.run_path(str(root / 'hw/syn/xilinx/ypcb/build_vivado.py'))['reuse_synthesis']
    original, output = tmp_path / 'original', tmp_path / 'output'
    original.mkdir()
    output.mkdir()
    cdc = ('// Date       : 2026-10-18 03:39:31\n'
           '(* ASYNC_REG = "TRUE" *) wire crossing;\n'
           '//  Auto-Generated by LiteX on 2026-10-18 03:39:31.\n')
    script = 'snapshot/hw/syn/xilinx/ypcb/vivado_board.tcl'
    files = {'cdc/ypcb_axi_cdc.v': cdc, 'wb-cdc/ypcb_wb_cdc.v': cdc,
             'snapshot/hw/rtl/dut.sv': '// Date       : 2026-10-18 03:39:31\nmodule dut; endmodule\n',
             'afu/sources.txt': str(original) + '/snapshot/hw/rtl/dut.sv\n',
             'afu/config.flags': '-DCH1\n',
             script: 'set_part part\nopen_checkpoint [file join $output_dir synth.dcp]\n'}
    previous, current = {}, {}
    for name, text in files.items():
        p = original / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        previous[name] = hashlib.sha256(p.read_bytes()).hexdigest()
        p = output / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text.replace(str(original), str(output)).replace('2026-10-18 03:39:31', '2026-10-20 09:03:47')
                     if name.startswith(('cdc/', 'wb-cdc/')) else text.replace(str(original), str(output)))
    target = output / 'cdc/ypcb_axi_cdc.v'
    if change == 'logic':
        target.write_text(target.read_text().replace('wire crossing', 'wire different_crossing'))
    elif change == 'attribute':
        target.write_text(target.read_text().replace('"TRUE"', '"FALSE"'))
    elif change == 'other_file':
        p = output / 'snapshot/hw/rtl/dut.sv'
        p.write_text(p.read_text().replace('2026-10-18', '2026-10-20'))
    for name in files:
        current[name] = hashlib.sha256((output / name).read_bytes()).hexdigest()
    (original / 'inputs.json').write_text(json.dumps({'inputs': previous}))
    (original / 'synthesize-exit.json').write_text(json.dumps({'exit_code': 0, 'interrupted': 0}))
    for name in ('synth.dcp', 'utilization-synth.rpt', 'drc-synth.rpt'):
        (original / name).write_bytes(b'compiled fixture')
    if change == 'timestamps':
        manifest = {'inputs': current}
        result = reuse(original, output, manifest)
        assert len(result['timestamp_only_regenerations']) == 2
        assert (output / 'synth.dcp').read_bytes() == b'compiled fixture'
        for name in ('cdc/ypcb_axi_cdc.v', 'wb-cdc/ypcb_wb_cdc.v'):
            assert (output / name).read_bytes() == (original / name).read_bytes()
            assert manifest['inputs'][name] == previous[name]
    else:
        with pytest.raises(ValueError, match='HDL or pin constraints changed'):
            reuse(original, output, {'inputs': current})
        assert not (output / 'synth.dcp').exists()
