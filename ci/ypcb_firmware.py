import hashlib
import json
from pathlib import Path
import re
import struct
import time

MEMORY_BYTES = 16384
CPU_RUNNING = 0x5ca10018
CPU_HELD = 0x5ca10019


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def controller_logic(path, firmware):
    text = path.read_text()
    seen = []
    words = struct.unpack('<4096I', firmware.ljust(MEMORY_BYTES, b'\0'))

    def replace(match):
        index, value = int(match[1]), int(match[2], 16)
        if index >= len(words) or value != words[index]:
            raise ValueError('Controller BRAM initialization differs from its firmware')
        seen.append(index)
        return f'selfcal_mem[{index}] = <FIRMWARE_WORD>;'

    text = re.sub(r"selfcal_mem\[(\d+)\] = 'h([0-9a-fA-F]+);", replace, text)
    if seen != list(range(4096)):
        raise ValueError('Expected one complete 16 KiB calibration BRAM initialization')
    text, count = re.subn(r'/\*\nLiteDRAMCore\n.*?\*/', '/* LiteDRAM hierarchy metadata */',
                          text, count=1, flags=re.S)
    if count != 1:
        raise ValueError('Unknown controller hierarchy metadata')
    text, count = re.subn(r'^// Date       : [0-9 :\-]+$', '// Date       : metadata', text, flags=re.M)
    if count != 1:
        raise ValueError('Unknown controller date metadata')
    text, count = re.subn(r'^//  Auto-Generated by LiteX on [0-9 :\-]+\.$',
                          '//  Auto-Generated by LiteX on metadata.', text, flags=re.M)
    if count != 1:
        raise ValueError('Unknown controller footer metadata')
    return text


def checked_firmware(directory):
    path = directory / 'selfcal_fw/manifest.json'
    metadata = json.loads(path.read_text())
    payload = (directory / 'selfcal_fw/firmware.bin').read_bytes()
    if (not payload or len(payload) > MEMORY_BYTES or len(payload) % 4
            or metadata['memory_bytes'] != MEMORY_BYTES or metadata['bytes'] != len(payload)
            or metadata['sha256'] != hashlib.sha256(payload).hexdigest()):
        raise ValueError('Invalid calibration firmware size or identity')
    return metadata, payload


def prepare_overlay(image, candidate, proof_file):
    image, candidate = Path(image), Path(candidate)
    original = image / 'ddr'
    inputs = json.loads((image / 'inputs.json').read_text())['inputs']
    for name in ('gateware/ypcb_ddr3.v', 'csr.json', 'software/include/generated/sdram_phy.h',
                 'selfcal_fw/manifest.json', 'selfcal_fw/firmware.bin'):
        if inputs.get('ddr/' + name) != digest(original / name):
            raise ValueError('Frozen controller input changed: ' + name)
    previous, old_payload = checked_firmware(original)
    firmware, payload = checked_firmware(candidate)
    identity = {}
    for name, expected in firmware['inputs'].items():
        if digest(Path(name)) != expected:
            raise ValueError('Firmware input changed: ' + name)
        if Path(name).name in identity:
            raise ValueError('Ambiguous firmware identity input')
        identity[Path(name).name] = expected
    identifier = int(hashlib.sha256(json.dumps(identity, sort_keys=True).encode()).hexdigest()[:8], 16)
    if identifier != firmware['firmware_id']:
        raise ValueError('Firmware identity does not match its compiled inputs')
    for name in ('csr.json', 'software/include/generated/sdram_phy.h'):
        if (candidate / name).read_bytes() != (original / name).read_bytes():
            raise ValueError('Firmware overlay changed controller configuration: ' + name)
    first = controller_logic(original / 'gateware/ypcb_ddr3.v', old_payload)
    second = controller_logic(candidate / 'gateware/ypcb_ddr3.v', payload)
    if first != second:
        raise ValueError('Firmware overlay changes FPGA logic or clocks')
    proof = json.loads(Path(proof_file).read_text())
    if (proof['status'] != 'NATIVE_DIAGNOSTIC_FIRMWARE_AND_RV32I_RTL_PASS_NO_HARDWARE_ACCESS'
            or proof['boot_firmware_sha256'] != previous['sha256']
            or proof['firmware']['sha256'] != firmware['sha256']
            or proof['firmware']['firmware_id'] != identifier
            or proof['rtl_exit']['exit_code'] != 0 or proof['rtl_exit']['interrupted'] != 0
            or proof['integrity']['status'] != 'PASS'
            or proof['integrity']['isa'] != 'RV32I'
            or proof['integrity']['unresolved_symbols']):
        raise ValueError('Diagnostic firmware lacks its matching native/CPU RTL proof')
    for name, expected in proof['source_sha256'].items():
        if digest(Path(name)) != expected:
            raise ValueError('Diagnostic proof input changed: ' + name)
    registers = json.loads((original / 'csr.json').read_text())['csr_registers']
    names = ('hold', 'status', 'state', 'mem_adr', 'mem_dat', 'mem_rdat', 'mbox_adr', 'mbox_dat')
    offsets = {name: 0x6000 + registers['ddrctrl_selfcal_' + name]['addr'] for name in names}
    if any(not 0x6000 <= address < 0x6800 or address % 4 for address in offsets.values()):
        raise ValueError('Calibration controls escape their original CH1 CSR bank')
    return {'original_firmware_id': previous['firmware_id'], 'firmware_id': identifier,
            'firmware_sha256': firmware['sha256'], 'firmware_bytes': len(payload),
            'controller_logic_sha256': hashlib.sha256(first.encode()).hexdigest(),
            'proof_sha256': digest(Path(proof_file)), 'offsets': offsets}, payload


def closed_memory(status):
    allowed = 2 | 8 | 32 | (1 << 15) | (7 << 16)
    return status & ~allowed == 0 and status & 3 == 2 and status >> 16 in (0, 4)


def upload_and_capture(mmio, payload, firmware_id, offsets, *, timeout=600,
                       cancelled=lambda: False, progress=lambda report: None, now=time.monotonic):
    if not payload or len(payload) > MEMORY_BYTES or len(payload) % 4 or timeout <= 0:
        raise ValueError('Invalid firmware upload bounds')
    deadline = now() + timeout
    report = {'words_written': 0, 'words_verified': 0, 'hold_requested': False,
              'restart_requested': False, 'hardware_memory_scope': 'calibration CPU BRAM only',
              'gpu_runtime_qualified': False}

    def check_time():
        if cancelled():
            raise InterruptedError('Calibration firmware upload interrupted')
        if now() >= deadline:
            raise TimeoutError('Calibration firmware upload timed out')

    def read(address):
        check_time()
        return mmio.read(address)

    def write(address, value):
        check_time()
        mmio.write(address, value)

    try:
        signature, version, board = read(0x3000), read(0x3004), read(0x3008)
        cpu, state = read(offsets['status']), read(offsets['state'])
        report.update(initial_board_status=board, initial_cpu_status=cpu, initial_state=state)
        if (signature != 0x56595043 or version != 3 or not closed_memory(board)
                or cpu not in (CPU_RUNNING, CPU_HELD) or state not in (2, 3)):
            raise ValueError('Firmware upload requires the quiescent ABI 3 calibration CPU')
        report['hold_requested'] = True
        write(offsets['hold'], 1)
        while True:
            cpu = read(offsets['status'])
            if cpu == CPU_HELD:
                break
            if cpu != CPU_RUNNING:
                raise ValueError('Calibration CPU status changed while holding')
        if not closed_memory(read(0x3008)):
            raise ValueError('Memory became active before firmware upload')
        words = struct.unpack('<4096I', payload.ljust(MEMORY_BYTES, b'\0'))
        for index, word in enumerate(words):
            write(offsets['mem_adr'], index)
            write(offsets['mem_dat'], word)
            report['words_written'] += 1
            if index % 256 == 255:
                progress(dict(report))
        actual = bytearray()
        for index, expected in enumerate(words):
            write(offsets['mem_adr'], index)
            word = read(offsets['mem_rdat'])
            if word != expected:
                raise ValueError(f'Calibration firmware readback mismatch at word {index}')
            actual += struct.pack('<I', word)
            report['words_verified'] += 1
            if index % 256 == 255:
                progress(dict(report))
        report['padded_readback_sha256'] = hashlib.sha256(actual).hexdigest()
        if not closed_memory(read(0x3008)) or read(offsets['status']) != CPU_HELD:
            raise ValueError('Board or CPU changed before verified restart')
        write(offsets['state'], 0)
        if read(offsets['state']) != 0:
            raise ValueError('Calibration CPU terminal state could not be cleared')
        report['restart_requested'] = True
        write(offsets['hold'], 0)
        if read(offsets['status']) != CPU_RUNNING:
            raise ValueError('Calibration CPU did not restart')
        while True:
            state = read(offsets['state'])
            if state in (2, 3):
                break
            if state not in (0, 1):
                raise ValueError('Unexpected restarted calibration state')
        if read(offsets['status']) != CPU_RUNNING:
            raise ValueError('Restarted calibration CPU faulted or was held')
        mailbox = []
        for index in range(128):
            write(offsets['mbox_adr'], index)
            mailbox.append(read(offsets['mbox_dat']))
        if mailbox[0] != 0x59444331 or mailbox[1] != firmware_id or mailbox[2] != state:
            raise ValueError('Restarted firmware result does not match the uploaded image')
        report.update(state=state, error=mailbox[3], failed_lane=mailbox[4], probes=mailbox[5],
                      max_row_cycles=mailbox[6], cycles=mailbox[7] | (mailbox[8] << 32),
                      write_slips=[(mailbox[15] >> (lane * 3)) & 7 for lane in range(9)],
                      mailbox=mailbox, final_board_status=read(0x3008))
        if mailbox[9] == 0x59444231:
            report['per_bit'] = {'lane': mailbox[10], 'valid_bits': mailbox[11],
                                 'error_or': mailbox[12], 'error_and': mailbox[13],
                                 'scan_settings': mailbox[14], 'windows': mailbox[104:112],
                                 'pass_counts': mailbox[112:120], 'masks': mailbox[120:128]}
        progress(dict(report))
        return report
    except BaseException:
        if report['hold_requested']:
            try:
                mmio.write(offsets['hold'], 1)
                report['held_after_failure'] = mmio.read(offsets['status']) == CPU_HELD
            except BaseException as error:
                report['hold_cleanup_error'] = repr(error)
        progress(dict(report))
        raise
